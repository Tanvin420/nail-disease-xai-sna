def blues_cmap():
    from matplotlib.colors import LinearSegmentedColormap

    return LinearSegmentedColormap.from_list("blues", ["#f7fafe"] + BLUES)


def save(fig, path: Path):
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path.with_suffix(".pdf"))
    fig.savefig(path.with_suffix(".png"), dpi=300)
    fig.savefig(path.with_suffix(".tiff"), dpi=600, pil_kwargs={"compression": "tiff_lzw"})
    plt.close(fig)
    print("figure", path.name)


def read(p: Path):
    return pd.read_csv(p) if p.exists() else None


def fmt(x, d=3):
    return "--" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{d}f}"


def latex_table(df: pd.DataFrame, path: Path, caption: str, label: str, colfmt: str | None = None):
    path.parent.mkdir(parents=True, exist_ok=True)
    cols = colfmt or "l" + "c" * (df.shape[1] - 1)
    esc = lambda s: str(s).replace("_", r"\_").replace("%", r"\%").replace("&", r"\&")  # noqa: E731
    L = [r"\begin{table}[!tbp]", r"\centering", rf"\caption{{{caption}}}", rf"\label{{{label}}}", r"\footnotesize",
         rf"\begin{{tabular}}{{{cols}}}", r"\hline", " & ".join(esc(c) for c in df.columns) + r" \\", r"\hline"]
    L += [" & ".join(esc(v) for v in row) + r" \\" for row in df.itertuples(index=False)]
    L += [r"\hline", r"\end{tabular}", r"\end{table}"]
    path.write_text("\n".join(L), encoding="utf-8")
    print("table ", path.name)


class Macros:
    def __init__(self):
        self.d = {}

    DIGITS = dict(zip("0123456789", ["Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine"]))

    def add(self, name: str, value, d: int = 3):
        """LaTeX macro names allow letters only: digits are spelled out (vgg16 -> VggOneSix)."""
        name = "".join(self.DIGITS.get(ch, ch) for ch in name)
        name = re.sub(r"[^A-Za-z]", "", "".join(w[:1].upper() + w[1:] for w in re.split(r"[_\W]+", name)))
        self.d[name] = value if isinstance(value, str) else fmt(float(value), d)

    def write(self, path: Path):
        path.write_text("% generated by scripts/s13_figures_tables.py - do not edit\n" +
                        "\n".join(rf"\newcommand{{\R{k}}}{{{v}}}" for k, v in sorted(self.d.items())) + "\n", encoding="utf-8")


